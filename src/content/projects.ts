/** False for empty values and for the explicit `TODO —` placeholders in the data. */
export function hasSuppliedCopy(value?: string): value is string {
  return Boolean(value && !value.startsWith('TODO'));
}

export function getPublishedProjects(): ProjectMeta[] {
  return PROJECTS.filter((p) => p.published);
}

export function getProjectBySlug(slug: string): ProjectMeta | undefined {
  return PROJECTS.find((p) => p.slug === slug);
}
